create or replace function public.noc_sync_promo_code() returns trigger language plpgsql set search_path='' as $$
begin
  insert into public.noc_promo_codes(partner_id,promo_code,code_type,city,role,channel,tracking_url,shopify_merch_code,status)
  values(new.id,new.promo_code,'partner',new.city,new.role,'partner',new.tracking_url,new.merch_code,case when new.status='active' then 'active' else 'draft' end)
  on conflict(promo_code) do update set partner_id=excluded.partner_id,city=excluded.city,role=excluded.role,tracking_url=excluded.tracking_url,shopify_merch_code=excluded.shopify_merch_code,status=excluded.status,updated_at=now();
  return new;
end $$;
